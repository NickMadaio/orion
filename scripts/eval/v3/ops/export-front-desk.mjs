// Write the frozen front-desk prompt into the plugin so production runs exactly what was measured
// (held-out 123/138 for qwen3.5:4b, p6 + restate). Re-run after re-freezing J1.
// Usage: node scripts/eval/v3/ops/export-front-desk.mjs [model]
// (Written by Claude on 2026-10-10 for the V3 implementation.)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";
const model = process.argv[2] ?? "qwen3.5:4b-q4_K_M";
const frozen = JSON.parse(readFileSync(join(homedir(), ".openclaw/orion-controlled/evals/v3/configs/j1", `${model.replace(/[:/]/g, "_")}.json`), "utf8"));
// A production rule on top of the frozen prompt: its "answer" drafts invented live facts ("Sunset is at
// 6:42 PM today.", "I haven't seen any new messages") that went out unchecked (live sweep, 2026-10-15).
const LIVE_DATA_RULE = "- Anything about live data — the weather, sunset or sunrise, his texts, messages or email, his day, calendar, focus session or supplements — is tool or escalate, never answer. You cannot know it.\n";
if (!frozen.system.includes("# Hard rules\n")) throw new Error("frozen prompt has no '# Hard rules' section to add the live-data rule to");
// The tasks tool had no "list", so "whats on my list rn" and "anything overdue?" read the calendar
// and got "nothing on the calendar today" (live sweep, 2026-10-15).
const TASKS_TOOL = ['- tasks: Add, change or finish one to-do. args: {"do":"add|set|done"', '- tasks: List his to-dos, or add, change or finish one. args: {"do":"list|add|set|done"'];
const TASKS_LIST_RULE = '- "Whats on my list", "what\'s due this week", "anything overdue?" → tool tasks with do "list". His to-dos are not on the calendar.\n';
const TODO_ADD_RULE = '- "Add X to my to-dos / to-do list" → tool tasks with do "add" and the title. Never ask what X means.\n';
for (const needle of [TASKS_TOOL[0], TODO_ADD_RULE]) if (!frozen.system.includes(needle)) throw new Error(`frozen prompt no longer has ${JSON.stringify(needle)}`);
const system = frozen.system.replace("# Hard rules\n", `# Hard rules\n${LIVE_DATA_RULE}`)
  .replace(TASKS_TOOL[0], TASKS_TOOL[1]).replace(TODO_ADD_RULE, `${TODO_ADD_RULE}${TASKS_LIST_RULE}`);
const out = `// GENERATED by scripts/eval/v3/ops/export-front-desk.mjs — do not edit by hand.
// The V3-frozen front-desk prompt for ${model} (config ${JSON.stringify(frozen.config)}, hash ${frozen.promptHash}), plus the live-data and to-do list rules.
export const FRONT_DESK_MODEL = ${JSON.stringify(model)};
export const FRONT_DESK_PROMPT_HASH = ${JSON.stringify(frozen.promptHash)};
export const FRONT_DESK_TEMPERATURE = ${JSON.stringify(frozen.config.temp ?? 0)};
export const FRONT_DESK_SYSTEM = ${JSON.stringify(system)};
`;
writeFileSync("plugin/orion-control/src/front-desk-prompt.ts", out);
console.log(`wrote front-desk-prompt.ts (${system.length} chars, hash ${frozen.promptHash})`);
