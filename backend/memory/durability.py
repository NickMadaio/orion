"""What it takes for something to become durable memory.

The manifest's rule -- arbitrary external content must not become durable memory
-- is not a filter on text. It is a rule about where a claim came from, and Phase
3 already records that: every piece of context carries a `Provenance`, and
anything nobody classified is `EXTERNAL_UNTRUSTED` by default.

So promotion needs GROUNDS, and the four the manifest names are the only ones.
Each is checked against provenance rather than trusted as a label, because a
caller that could simply assert "the user confirmed this" is a caller that will.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum

from orion.core.context.domains import Provenance


#: How many independent observations count as "strong repeated evidence".
#: Three, and from a non-external source: twice is a coincidence, and any number
#: of repetitions of something read on a web page is still that web page.
REPETITION_THRESHOLD = 3


class Grounds(str, Enum):
    """The manifest's four, and nothing else."""

    USER_ASSERTION = "explicit_user_assertion"
    USER_CONFIRMATION = "explicit_user_confirmation"
    REPEATED_EVIDENCE = "strong_repeated_evidence"
    APPROVED_SYSTEM_STATE = "approved_structured_system_state"


class PromotionRefused(ValueError):
    """This could not become durable memory, and the reason says which rule."""


@dataclass(frozen=True, slots=True)
class Evidence:
    """What the caller offers in support of making something permanent."""

    grounds: Grounds
    provenance: Provenance
    observations: int = 1
    approved_by: str | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "grounds", Grounds(self.grounds))
        object.__setattr__(self, "provenance", Provenance(self.provenance))
        if type(self.observations) is not int or self.observations < 1:
            raise ValueError("observations start at 1")


#: Provenances that can never support permanence, whatever grounds are claimed.
#:
#: ORION_INFERRED is on this list and that is the point. Phase 3 already refused
#: to call inference authoritative; "Orion concluded this" hardening into a
#: permanent fact about a person is exactly what that refusal was protecting
#: against.
NEVER_DURABLE = frozenset({Provenance.EXTERNAL_UNTRUSTED, Provenance.ORION_INFERRED})


def check(evidence: Evidence) -> None:
    """Raise unless this evidence genuinely supports permanence."""

    if evidence.provenance in NEVER_DURABLE:
        raise PromotionRefused(
            f"{evidence.provenance.value} can never become durable memory, "
            f"whatever grounds are claimed"
        )

    if evidence.grounds is Grounds.USER_ASSERTION:
        if evidence.provenance is not Provenance.USER_ASSERTED:
            raise PromotionRefused("an assertion has to have come from the user")
        return

    if evidence.grounds is Grounds.USER_CONFIRMATION:
        if evidence.provenance is not Provenance.USER_CONFIRMED:
            raise PromotionRefused("a confirmation has to be something the user was asked")
        return

    if evidence.grounds is Grounds.REPEATED_EVIDENCE:
        if evidence.observations < REPETITION_THRESHOLD:
            raise PromotionRefused(
                f"{evidence.observations} observation(s); "
                f"{REPETITION_THRESHOLD} are needed for repeated evidence"
            )
        if evidence.provenance not in {Provenance.DEVICE_OBSERVED, Provenance.SYSTEM_GENERATED}:
            # Repetition of something read is still that reading. Only what the
            # system or a device observed can accumulate into a fact.
            raise PromotionRefused(
                "repeated evidence must be observed by a device or generated by the system"
            )
        return

    if evidence.grounds is Grounds.APPROVED_SYSTEM_STATE:
        if evidence.provenance is not Provenance.SYSTEM_GENERATED:
            raise PromotionRefused("approved system state must be system-generated")
        if not evidence.approved_by:
            raise PromotionRefused("approved system state records who approved it")
        return

    raise PromotionRefused(f"unknown grounds: {evidence.grounds}")


def permits(evidence: Evidence) -> bool:
    try:
        check(evidence)
    except PromotionRefused:
        return False
    return True
