//
//  What the outside world is asked to do, and why each request can be made
//  twice without doing damage.
//
//  `reconcile(now:)` is pure and changes nothing. It returns a list of effects,
//  and the service carries them out. The separation matters because the service
//  can crash between the two, and after a restart `reconcile` runs again over
//  the same state and produces the same list.
//
//  So every effect has a STABLE, DERIVED id — a function of the session, the
//  phase and what kind of effect it is, never of when it was produced. The
//  service acknowledges an effect only once it has actually been carried out,
//  and an acknowledged effect is filtered out of every later reconciliation.
//  That is what stops a crash from speaking the same transition line twice or
//  writing a second history record for one session, which is the thing the plan
//  singles out as unacceptable.
//
//  Acknowledging is itself a command, so it goes through the single writer and
//  is persisted with everything else.
//

import Foundation

// MARK: - Effects

public enum Effect: Equatable, Sendable, Identifiable {

    /// Say something out loud, through Orion's real voice.
    case announce(id: EffectID, Announcement)

    /// Begin the clip for a phase.
    case startClip(id: EffectID, clip: ClipAssignment, phaseIndex: Int)

    /// Stop whatever is playing.
    case stopClip(id: EffectID)

    /// Append one record to `focus-history.jsonl`. Exactly once per session,
    /// ever — the id has no phase component for that reason.
    case appendHistory(id: EffectID, HistoryRecord)

    /// The app was not running, or nobody was here, for long enough that
    /// counting it would be a lie. Ask rather than decide.
    case askAboutAbsence(id: EffectID, seconds: TimeInterval, phaseIndex: Int)

    /// The wall clock moved by an amount that is not real time passing.
    case reportClockAnomaly(id: EffectID, seconds: TimeInterval)

    public var id: EffectID {
        switch self {
        case .announce(let id, _),
             .startClip(let id, _, _),
             .stopClip(let id),
             .appendHistory(let id, _),
             .askAboutAbsence(let id, _, _),
             .reportClockAnomaly(let id, _):
            return id
        }
    }
}

// MARK: - Announcements

/// What to say, as a fact rather than as a string.
///
/// The domain does not write prose. Break prompts are generated by Orion, and
/// the exact wording of a transition is a presentation concern that will change
/// without the session engine changing. Keeping this typed means the tests
/// assert on WHAT is announced, not on a sentence that a copy edit would break.
public enum Announcement: Equatable, Sendable {
    case sessionStarted(task: String, totalMinutes: Int)
    case focusBeginning(blockNumber: Int, ofBlocks: Int, minutes: Int)
    case restBeginning(minutes: Int)
    case restEnding
    case sessionComplete(focusMinutes: Int)
    case sessionEndedEarly(focusMinutes: Int)
    case waitingForReturn
    case paused
    case resumed
}

// MARK: - History

/// One line of `focus-history.jsonl`. Append-only, never pruned.
///
/// Durations are stored in seconds as measured, and separately from what was
/// planned, so a later question like "did he actually do the fifty minutes"
/// has an answer. Storing only the plan would make every session look perfect.
public struct HistoryRecord: Codable, Equatable, Sendable {
    public let sessionID: String

    /// Local logical day, 4 am cutoff, from `OrionDay`. Never a UTC date.
    public let dayKey: String

    public let task: String
    public let startedAt: Date
    public let endedAt: Date
    public let reason: FinishReason

    /// What was planned, and what was actually served.
    public let plannedFocusSeconds: TimeInterval
    public let servedFocusSeconds: TimeInterval
    public let plannedRestSeconds: TimeInterval
    public let servedRestSeconds: TimeInterval

    /// How many focus blocks were completed in full.
    public let completedFocusBlocks: Int
    public let totalFocusBlocks: Int

    /// Time deliberately not counted — downtime, long absences, paused stretches.
    public let uncountedSeconds: TimeInterval

    /// True when any measurement in this record had to fall back to the wall
    /// clock, or when the clock moved. Makes an approximate record legible as
    /// approximate instead of presenting an estimate as a measurement.
    public let approximate: Bool

    public init(sessionID: String, dayKey: String, task: String,
                startedAt: Date, endedAt: Date, reason: FinishReason,
                plannedFocusSeconds: TimeInterval, servedFocusSeconds: TimeInterval,
                plannedRestSeconds: TimeInterval, servedRestSeconds: TimeInterval,
                completedFocusBlocks: Int, totalFocusBlocks: Int,
                uncountedSeconds: TimeInterval, approximate: Bool) {
        self.sessionID = sessionID
        self.dayKey = dayKey
        self.task = task
        self.startedAt = startedAt
        self.endedAt = endedAt
        self.reason = reason
        self.plannedFocusSeconds = plannedFocusSeconds
        self.servedFocusSeconds = servedFocusSeconds
        self.plannedRestSeconds = plannedRestSeconds
        self.servedRestSeconds = servedRestSeconds
        self.completedFocusBlocks = completedFocusBlocks
        self.totalFocusBlocks = totalFocusBlocks
        self.uncountedSeconds = uncountedSeconds
        self.approximate = approximate
    }
}

// MARK: - Effect naming

/// The kinds, as strings, in one place.
///
/// They are part of the persisted acknowledgement set, so renaming one silently
/// un-acknowledges every effect of that kind on disk and Orion says everything
/// again. Change these only with a migration.
public enum EffectKindName {
    public static let sessionStarted = "session-started"
    public static let phaseAnnounce = "phase-announce"
    public static let phaseClip = "phase-clip"
    public static let clipStop = "clip-stop"
    public static let history = "history"
    public static let absence = "absence"
    public static let clockAnomaly = "clock-anomaly"
    public static let waitingForReturn = "waiting-for-return"
    public static let finishAnnounce = "finish-announce"
}
