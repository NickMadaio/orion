//
//  The one way anything asks the session to change.
//
//  Voice, the dashboard, the Console and a script over IPC all send the same
//  typed command. There is no second path, and in particular no path that
//  writes state directly — `SessionService` is the single writer and this is
//  its vocabulary. That is what stops the two-writers problem the health log
//  already had once.
//
//  Every command carries a `RequestID`, and the reducer refuses one it has
//  already applied. This is not defensive decoration: a caller that times out
//  and retries is the normal case over IPC, and without idempotency the retry
//  of "pause" would land as a second pause, or the retry of "finish" would
//  append a second history record for one session.
//
//  Commands also carry their ORIGIN. A sentence generated by a Console keypress
//  is not automatically trusted user speech, and the origin has to survive all
//  the way through authorization and into the ledger rather than being inferred
//  from the shape of the text downstream.
//

import Foundation

// MARK: - Origin

/// Where a command came from, carried through unchanged.
public enum CommandOrigin: String, Codable, Sendable {
    /// Nick said it out loud and the speaker verifier was satisfied.
    case voice
    /// A control in Orion's own UI.
    case dashboard
    /// The keyboard-first Console. Typed, trusted, but NOT speech.
    case console
    /// A script over the local IPC socket.
    case script
    /// The service acting on its own schedule — a phase boundary arriving.
    case scheduler
}

// MARK: - Commands

public struct Command: Codable, Equatable, Sendable {
    public let requestID: RequestID
    public let origin: CommandOrigin

    /// When the CALLER issued it, which is not when the reducer applies it.
    /// Kept because a command delayed in a queue should not be treated as
    /// having happened at delivery time.
    public let issuedAt: Date

    public let kind: CommandKind

    public init(requestID: RequestID, origin: CommandOrigin,
                issuedAt: Date, kind: CommandKind) {
        self.requestID = requestID
        self.origin = origin
        self.issuedAt = issuedAt
        self.kind = kind
    }
}

public enum CommandKind: Codable, Equatable, Sendable {

    /// Begin a session. Refused if one is already running — the caller has to
    /// finish or abandon first, because two live sessions have no meaning and
    /// silently replacing one would throw away served minutes.
    case start(plan: SessionPlan)

    case pause
    case resume

    /// End the current break early and go straight to the next focus block.
    /// Nick's call, always allowed, and recorded so the archive is honest about
    /// the break being short.
    case skipRest

    /// Shorten the current break to a specific remaining duration.
    case shortenRest(to: TimeInterval)

    /// Nick says he is done. Archived as a SUCCESS — this is the agreed policy,
    /// not a failure state. Another block may be offered but never imposed.
    case finishEarly

    /// Something went wrong, or Nick walked away and never came back. Archived
    /// as abandoned, which is a different fact from finishing early.
    case abandon

    /// The sensors say Nick is not here. Does not itself pause anything; the
    /// reducer decides what an idle hold means for the phase that is running.
    case noteIdle

    /// He is back.
    case noteReturned

    /// An effect has been carried out and must never be carried out again.
    /// Separate from the effect being EMITTED, which is the whole point: a
    /// crash in between leaves the effect unacknowledged and it is re-emitted,
    /// while a crash after acknowledgement leaves it done and it is not.
    case acknowledgeEffect(EffectID)
}

// MARK: - Rejections

/// Why a command did not apply.
///
/// A rejection is a first-class result rather than a thrown error, because the
/// caller has to be able to tell "you already did this" from "that is not
/// possible right now" — the first is success from the caller's point of view
/// and the second is not.
public enum CommandRejection: Equatable, Sendable {
    /// This exact request has already been applied. The caller retried; the
    /// state is what they wanted. Treat as success.
    case alreadyApplied(RequestID)

    /// No session is running and this command needs one.
    case noSession

    /// A session is already running and `start` will not replace it.
    case sessionAlreadyRunning(SessionID)

    /// The session is over. Nothing further applies to it.
    case sessionFinished(SessionID)

    /// The command makes no sense in the current phase — shortening a rest
    /// while a focus block is running, for instance.
    case notApplicable(String)

    /// The plan itself is not runnable.
    case invalidPlan(String)

    public var isAlreadyApplied: Bool {
        if case .alreadyApplied = self { return true }
        return false
    }

    /// What to say out loud. Deliberately plain: these reach Nick.
    public var message: String {
        switch self {
        case .alreadyApplied:
            return "Already done."
        case .noSession:
            return "There is no session running."
        case .sessionAlreadyRunning:
            return "A session is already running. Finish or abandon it first."
        case .sessionFinished:
            return "That session has already ended."
        case .notApplicable(let why):
            return why
        case .invalidPlan(let why):
            return "That session plan will not run: \(why)"
        }
    }
}
