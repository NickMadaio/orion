// Write the V3-frozen worker instructions into the plugin (production appends them per job).
// Scheduling = the 9B's J6 prompt (J3 coach guide + multi-turn section + full reschedule usage +
// honesty/rules + examples); brain = the 9B's J5 prompt; general tools = the J2 exec command reference + honesty + rules.
// Usage: node scripts/eval/v3/ops/export-job-instructions.mjs [model]
// (Written by Claude on 2026-10-10 for the V3 implementation.)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";
const model = process.argv[2] ?? "qwen3.5:9b";
const slug = model.replace(/[:/]/g, "_");
const frozen = (job) => JSON.parse(readFileSync(join(homedir(), ".openclaw/orion-controlled/evals/v3/configs", job, `${slug}.json`), "utf8"));
const blocks = JSON.parse(readFileSync("scripts/eval/v3/prompts/blocks.json", "utf8"));
const j6 = frozen("j6"); const j5 = frozen("j5");
// Production fixes to the to-do commands on top of the frozen prompts (live sweep, 2026-10-15): they
// offered `orion-tasks done` (it did not exist) and `orion-agenda … --todos` (never did), "whats on my
// list" read the calendar, and "due friday" after an add ran a second add — two copies of the to-do.
const TODO_PATCHES = {
  general: [
    [" | day <date> [--todos]\n", " | day <date>\n"],
    ['- orion-tasks add "<title>" [--due <day>] | done "<title>"\n',
      '- orion-tasks list | add "<title>" [--due <day>] | set "<title>" --due <day> | done "<title>"\n' +
      '  His to-do list, what is due, what is overdue → orion-tasks list (his to-dos are not on the calendar).\n' +
      '  A due date, priority or new name for a to-do he just added → orion-tasks set "<title>" --due <day>, never a second add.\n'],
  ],
  scheduling: [
    ['  orion-tasks plan ["<task>"] [--days 7]\n',
      '  orion-tasks done "<task>"                    tick ONE to-do off (NOTHING WAS CHANGED: nothing was ticked off)\n  orion-tasks plan ["<task>"] [--days 7]\n'],
    ["A to-do (not a calendar block) → `orion-tasks add`.\n",
      "A to-do (not a calendar block) → `orion-tasks add`. A due date, priority or new name for a to-do he just added → `orion-tasks set`, never a second `orion-tasks add`. His to-do list, what is due or overdue → `orion-tasks list`.\n"],
  ],
};
const patch = (text, pairs, job) => pairs.reduce((t, [from, to]) => {
  if (!t.includes(from)) throw new Error(`${job} prompt no longer has ${JSON.stringify(from)} to patch`);
  return t.replace(from, to);
}, text);
const general = patch([readFileSync("scripts/eval/v3/prompts/j2/p0.md", "utf8").trim(), blocks.honesty, blocks.rules].filter(Boolean).join("\n\n"), TODO_PATCHES.general, "general");
const out = `// GENERATED by scripts/eval/v3/ops/export-job-instructions.mjs — do not edit by hand.
// V3-frozen worker instructions for ${model}: scheduling ${j6.promptHash} (J6 ${JSON.stringify(j6.config)}),
// brain ${j5.promptHash} (J5 ${JSON.stringify(j5.config)}), general = J2 command reference (exec) + honesty + rules blocks.
export const WORKER_MODEL = ${JSON.stringify(model)};
export const SCHEDULING_INSTRUCTIONS = ${JSON.stringify(patch(j6.system, TODO_PATCHES.scheduling, "scheduling"))};
export const BRAIN_INSTRUCTIONS = ${JSON.stringify(j5.system)};
export const GENERAL_INSTRUCTIONS = ${JSON.stringify(general)};
`;
writeFileSync("plugin/orion-control/src/job-instructions.ts", out);
console.log(`wrote job-instructions.ts: scheduling ${j6.system.length}, brain ${j5.system.length}, general ${general.length} chars`);
